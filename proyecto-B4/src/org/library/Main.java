package org.library;

import org.library.enums.LoanStatus;
import org.library.enums.RequestStatus;
import org.library.enums.Role;
import org.library.model.*;

import java.time.LocalDate;
import java.util.Scanner;

public class Main {
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in); 
        
        System.out.println("========================================");
        System.out.println("  LIBRARY MANAGEMENT SYSTEM            ");
        System.out.println("========================================");

        // 1. Instanciación en inglés
        User estudiante = new User(1, "EST-2026", "Carlos", "Perez", "carlos@correo.com", "hash123", Role.STUDENT, true);
        User bibliotecario = new User(2, "BIB-007", "Ana", "Gomez", "ana@correo.com", "hash456", Role.LIBRARIAN, true);
        Book libro = new Book(101, "978-3-16-148410-0", "Design Patterns", "Erich Gamma", "Addison-Wesley", 1994, 5, 5, true);

        System.out.println("[INFO] Initial data created successfully.");
        System.out.println("Student: " + estudiante.getFirst_name() + " " + estudiante.getLast_name());
        System.out.println("Book available: '" + libro.getTitle() + "' (Stock: " + libro.getAvailable_stock() + ")");
        System.out.println("----------------------------------------\n");

        System.out.println("Press ENTER to simulate a Loan Request...");
        scanner.nextLine();

        // 2. Flujo de Solicitud (Usa RequestStatus.PENDING)
        LoanApplication solicitud = new LoanApplication(501, estudiante.getUser_id(), LocalDate.now(), RequestStatus.PENDING, "None", null, null);
        RequestDetails solDetalle = new RequestDetails(901, solicitud.getRequest_id(), libro.getBook_id(), 1);

        System.out.println("[PROCESS] Request #" + solicitud.getRequest_id() + " generated by student.");
        System.out.println("Current status: " + solicitud.getStatus());
        System.out.println("----------------------------------------\n");

        System.out.println("Press ENTER for Librarian approval...");
        scanner.nextLine();

        // 3. Aprobación por el Bibliotecario (Usa RequestStatus.APPROVED)
        solicitud.setStatus(RequestStatus.APPROVED);
        solicitud.setLibrarian_id(bibliotecario.getUser_id());
        solicitud.setResponse_date(LocalDate.now());
        solicitud.setObservation("Approved after manual stock check.");

        // 4. Generación de Préstamo (Usa LoanStatus.ACTIVE)
        Loan prestamo = new Loan(701, solicitud.getRequest_id(), solicitud.getStudent_id(), solicitud.getLibrarian_id(), LocalDate.now(), LocalDate.now().plusDays(7), LoanStatus.ACTIVE);
        LoanDetails presDetalle = new LoanDetails(801, prestamo.getLoan_id(), libro.getBook_id(), solDetalle.getQuantity(), 0);

        // Descontar inventario de forma lógica
        libro.setAvailable_stock(libro.getAvailable_stock() - presDetalle.getQuantity());

        System.out.println("[SUCCESS] Loan generated successfully!");
        System.out.println("Loan ID: " + prestamo.getLoan_id());
        System.out.println("Status: " + prestamo.getStatus());
        System.out.println("Due Date: " + prestamo.getDue_date());
        System.out.println("New available stock for '" + libro.getTitle() + "': " + libro.getAvailable_stock());
        System.out.println("========================================");
        
        scanner.close();
    }
}
